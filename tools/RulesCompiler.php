<?php

/**
 * Turns a compact rules table (words, not regexes) into a real pack file.
 *
 *   php bin/rules-build.php rules/bikes.rules.php --out=packs/bikes.php
 *
 * The table is shorter than a pack because every `phrases` list becomes one
 * ordered regex, with the literals escaped for you. Row order is priority: the
 * first row wins, exactly like the engine. The compiler refuses to emit a table
 * where a phrase is caught by a broader row above it, because that is the bug
 * that makes "is it negotiable?" quote the asking price.
 */
final class RulesCompiler
{
    /** @param array<string, mixed> $table */
    public static function compile(array $table, string $source = 'the rules table', bool $force = false): string
    {
        $problems = self::ambiguities($table);

        if ($problems !== [] && ! $force) {
            throw new RuntimeException(
                "Refusing to build: " . count($problems) . " ambiguous rule(s).\n  - "
                    . implode("\n  - ", $problems)
                    . "\nReorder the rows so the narrower rule is above the broader one, or pass --force."
            );
        }

        $pack = ['name' => (string) ($table['name'] ?? 'pack')];

        foreach (['tools', 'nouns', 'types', 'criteria', 'aliases', 'areas'] as $key) {
            if (isset($table[$key])) {
                $pack[$key] = $table[$key];
            }
        }

        $facts = [];

        foreach ((array) ($table['facts'] ?? []) as $row) {
            $row = (array) $row;
            $key = (string) ($row['key'] ?? '');

            if ($key === '') {
                throw new RuntimeException('Every facts row needs a "key".');
            }

            $entry = ['match' => self::pattern($row['phrases'] ?? $row['match'] ?? [])];

            foreach (['fact', 'defer'] as $field) {
                if (isset($row[$field]) && (string) $row[$field] !== '') {
                    $entry[$field] = (string) $row[$field];
                }
            }

            $facts[$key] = $entry;
        }

        if ($facts !== []) {
            $pack['facts'] = $facts;
        }

        foreach (['process', 'agency', 'intents'] as $key) {
            $section = [];

            foreach ((array) ($table[$key] ?? []) as $topic => $phrases) {
                $section[(string) $topic] = self::pattern($phrases);
            }

            if ($section !== []) {
                $pack[$key] = $section;
            }
        }

        $header = "/**\n * Generated by bin/rules-build.php from {$source}.\n"
            . " * Edit that table and rebuild: this file is overwritten.\n */";

        if ($problems !== []) {
            $header .= "\n\n/*\n * Built with --force. Known ambiguity, fix the table:\n *   - "
                . implode("\n *   - ", $problems) . "\n */";
        }

        return "<?php\n\n" . $header . "\n\nreturn " . self::export($pack, 0) . ";\n";
    }

    /**
     * @param  array<string, mixed>  $table
     * @return list<string>
     */
    public static function ambiguities(array $table): array
    {
        $rows = array_values(array_map(fn($row): array => (array) $row, (array) ($table['facts'] ?? [])));

        if (count($rows) < 2) {
            return [];
        }

        $patterns = array_map(fn(array $row): string => self::pattern($row['phrases'] ?? $row['match'] ?? []), $rows);
        $out = [];

        foreach ($rows as $index => $row) {
            foreach (self::literals($row['phrases'] ?? []) as $phrase) {
                $text = self::normalise($phrase);
                $caughtBy = null;

                foreach ($patterns as $candidate => $pattern) {
                    if (@preg_match($pattern, $text) === 1) {
                        $caughtBy = $candidate;
                        break;
                    }
                }

                if ($caughtBy === null || $caughtBy === $index) {
                    continue;
                }

                $out[] = 'phrase "' . $phrase . '" is listed under fact "' . self::rowKey($row) . '" but the pattern of fact "'
                    . self::rowKey($rows[$caughtBy]) . '", which sits above it, catches that phrase first';
            }
        }

        return array_values(array_unique($out));
    }

    /** One ordered regex out of a list of ordinary phrases. */
    private static function pattern(mixed $phrases): string
    {
        if (is_string($phrases)) {
            return $phrases;
        }

        $parts = [];

        foreach ((array) $phrases as $phrase) {
            $phrase = self::clean((string) $phrase);

            if ($phrase === '') {
                continue;
            }

            $parts[] = (preg_match('/^\w/u', $phrase) === 1 ? '\b' : '')
                . preg_quote($phrase, '~')
                . (preg_match('/\w$/u', $phrase) === 1 ? '\b' : '');
        }

        if ($parts === []) {
            throw new RuntimeException('A rule has no usable phrase.');
        }

        return '~' . implode('|', array_unique($parts)) . '~i';
    }

    /** @return list<string> */
    private static function literals(mixed $phrases): array
    {
        if (is_string($phrases) || ! is_array($phrases)) {
            return [];
        }

        $out = [];

        foreach ($phrases as $phrase) {
            $phrase = self::clean((string) $phrase);

            if ($phrase !== '') {
                $out[] = $phrase;
            }
        }

        return $out;
    }

    private static function clean(string $phrase): string
    {
        $phrase = self::normalise($phrase);
        $phrase = (string) preg_replace("/[^\p{L}\p{N} '+\-%?]/u", ' ', $phrase);

        // A trailing question mark belongs to the sentence, not to the phrase:
        // "how much?" must still catch "how much is it".
        return rtrim(trim((string) preg_replace('/\s+/', ' ', $phrase)), '?.,!;:');
    }

    private static function normalise(string $text): string
    {
        $text = mb_strtolower(trim($text));

        return trim((string) preg_replace('/\s+/', ' ', $text));
    }

    /** @param array<string, mixed> $row */
    private static function rowKey(array $row): string
    {
        return (string) ($row['key'] ?? '?');
    }

    private static function export(mixed $value, int $depth): string
    {
        if (! is_array($value)) {
            return var_export($value, true);
        }

        if ($value === []) {
            return '[]';
        }

        $pad = str_repeat('    ', $depth);
        $list = array_is_list($value);
        $lines = [];

        foreach ($value as $key => $item) {
            $prefix = $list ? '' : var_export((string) $key, true) . ' => ';
            $lines[] = $pad . '    ' . $prefix . self::export($item, $depth + 1) . ',';
        }

        return "[\n" . implode("\n", $lines) . "\n" . $pad . ']';
    }
}
