<?php

/**
 * Generates the one port a tool genuinely cannot finish for you: the Catalogue.
 *
 * Given a small db spec (table, a column map, and which columns are safe to
 * state as facts) it writes a PDO-backed Catalogue and, if you keep leads in
 * your own table, a LeadSink adapter. Every column you did NOT mark answerable
 * comes out as a comment, not a value — facts() stays silent so the rule defers.
 * That is the same "draft safe, promote later" rule RulesDrafter follows for the
 * rules table, applied to code.
 *
 * The other two ports need no generation: AssistantKit\Pdo\PdoStore and
 * AssistantKit\Pdo\PdoLeads already work on any PDO connection. This class only
 * prints the wiring that binds all four together.
 */
final class PortScaffolder
{
    /**
     * @param  array<string, mixed>  $spec
     * @return array{catalogue: string, leads: string, wiring: string, classes: array{catalogue: string, leads: string}}
     */
    public static function fromSpec(array $spec): array
    {
        $name = self::className($spec['name'] ?? 'site');
        $db = $spec['db'] ?? null;

        if (! is_array($db)) {
            throw new InvalidArgumentException('The spec needs a "db" object (table, columns, facts).');
        }

        return [
            'catalogue' => self::renderCatalogue($name, $db),
            'leads' => self::renderLeads($name, $db),
            'wiring' => self::renderWiring($name),
            'classes' => ['catalogue' => $name . 'Catalogue', 'leads' => $name . 'Leads'],
        ];
    }

    /**
     * @param  array<string, mixed>  $db
     */
    private static function renderCatalogue(string $name, array $db): string
    {
        $table = self::identifier($db['table'] ?? 'items', 'table');
        $columns = $db['columns'] ?? [];
        $slug = self::identifier($columns['slug'] ?? 'slug', 'columns.slug');
        $title = self::identifier($columns['title'] ?? 'title', 'columns.title');
        $url = self::identifier($columns['url'] ?? 'url', 'columns.url');
        $criteria = self::renderCriteria($db['criteria'] ?? []);
        $facts = self::renderFacts($db['facts'] ?? []);

        $class = $name . 'Catalogue';

        return <<<PHP
        <?php

        /**
         * A Catalogue over PDO, generated by bin/kit-scaffold.php.
         *
         * This runs as written, but only answers the facts you marked. A fact with
         * no `column` in the spec is left as a comment: add the column and the
         * sentence once you have confirmed the value is safe to state in chat.
         */

        use AssistantKit\\Contracts\\Catalogue;

        final class {$class} implements Catalogue
        {
            public function __construct(private readonly PDO \$pdo) {}

            public function search(array \$criteria, int \$limit): array
            {
                \$where = [];
                \$bind = [];
        {$criteria}
                \$sql = 'SELECT * FROM {$table}';

                if (\$where !== []) {
                    \$sql .= ' WHERE ' . implode(' AND ', \$where);
                }

                \$count = \$this->pdo->prepare('SELECT COUNT(*) FROM (' . \$sql . ') filtered');
                \$count->execute(\$bind);
                \$total = (int) \$count->fetchColumn();

                \$statement = \$this->pdo->prepare(\$sql . ' LIMIT ' . max(1, \$limit));
                \$statement->execute(\$bind);

                \$items = array_map(\$this->toItem(...), \$statement->fetchAll(PDO::FETCH_ASSOC));

                return ['total' => \$total, 'items' => \$items];
            }

            public function find(string \$slug): ?array
            {
                \$statement = \$this->pdo->prepare('SELECT * FROM {$table} WHERE {$slug} = ?');
                \$statement->execute([\$slug]);
                \$row = \$statement->fetch(PDO::FETCH_ASSOC);

                return \$row === false ? null : \$row;
            }

            public function facts(array \$item): array
            {
                \$facts = [];
        {$facts}
                return \$facts;
            }

            /** @param array<string, mixed> \$row @return array<string, mixed> */
            private function toItem(array \$row): array
            {
                return [
                    'slug' => \$row['{$slug}'] ?? null,
                    'title' => \$row['{$title}'] ?? null,
                    'url' => \$row['{$url}'] ?? null,
                ] + \$row;
            }
        }

        PHP;
    }

    /**
     * @param  array<string, mixed>  $db
     */
    private static function renderLeads(string $name, array $db): string
    {
        $leads = $db['leads'] ?? null;

        if (! is_array($leads)) {
            return self::commentBlock(
                'No "db.leads" in the spec, so no site LeadSink was generated.',
                'Use AssistantKit\\Pdo\\PdoLeads (it makes its own table), or add'
                    . "\n * \"leads\": {\"table\": \"...\", \"columns\": {...}} to the spec and re-run.",
            );
        }

        $table = self::identifier($leads['table'] ?? 'enquiries', 'db.leads.table');
        $columns = $leads['columns'] ?? [];

        $keys = [];
        $placeholders = [];
        $values = [];

        foreach (['name', 'email', 'phone', 'message', 'item', 'source', 'chat'] as $field) {
            if (! isset($columns[$field])) {
                continue;
            }

            $column = self::identifier($columns[$field], "db.leads.columns.{$field}");
            $keys[] = $column;
            $placeholders[] = '?';
            $default = $field === 'source' ? "'chat'" : 'null';
            $values[] = "\$lead['{$field}'] ?? {$default}";
        }

        if ($keys === []) {
            throw new InvalidArgumentException('db.leads.columns must map at least one field to a column.');
        }

        $class = $name . 'Leads';
        $columnList = implode(', ', $keys);
        $bindList = implode(",\n            ", $values);
        $marks = implode(', ', $placeholders);

        return <<<PHP
        <?php

        /**
         * A LeadSink that writes into your existing {$table} table, generated by
         * bin/kit-scaffold.php. Extend this to fire your own autoresponder or CRM
         * call after the insert; the engine only needs the reference back.
         */

        use AssistantKit\\Contracts\\LeadSink;

        final class {$class} implements LeadSink
        {
            public function __construct(private readonly PDO \$pdo) {}

            public function capture(array \$lead): string
            {
                \$statement = \$this->pdo->prepare(
                    'INSERT INTO {$table} ({$columnList}) VALUES ({$marks})'
                );
                \$statement->execute([
            {$bindList},
                ]);

                return (string) \$this->pdo->lastInsertId();
            }
        }

        PHP;
    }

    private static function renderWiring(string $name): string
    {
        $catalogueClass = $name . 'Catalogue';

        return <<<PHP
        <?php

        // Wiring the four ports together. Copy into your bootstrap / route.
        // PdoStore and PdoLeads are ready-made; only the {$catalogueClass} was generated.

        use AssistantKit\\Assistant;
        use AssistantKit\\Pdo\\PdoLeads;
        use AssistantKit\\Pdo\\PdoStore;

        \$pdo = new PDO(\$dsn, \$username, \$password, [
            PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        ]);

        // First run only: build the chat tables. Skip if you bind your own store.
        (new PdoStore(\$pdo))->migrate();

        \$assistant = Assistant::fromConfig(
            \$kitRoot,
            new {$catalogueClass}(\$pdo),
            new PdoStore(\$pdo),
            // swap this for your {$name}Leads if leads live in your own table:
            new PdoLeads(\$pdo),
            null, // null = rules-only. Pass a LanguageModel to enable the AI layer.
        );

        \$reply = \$assistant->reply(\$chatId, \$message, \$itemSlug);

        PHP;
    }

    /**
     * @param  array<string, mixed>  $criteria
     */
    private static function renderCriteria(array $criteria): string
    {
        $modes = [
            'exact' => ['%s = ?', "\$criteria['%k']"],
            'like' => ["%s LIKE ?", "'%' . \$criteria['%k'] . '%'"],
            'min' => ['%s >= ?', "\$criteria['%k']"],
            'max' => ['%s <= ?', "\$criteria['%k']"],
        ];

        $lines = [];

        foreach ($criteria as $key => $definition) {
            $column = self::identifier(is_array($definition) ? ($definition['column'] ?? $key) : $definition, "criteria.{$key}");
            $mode = is_array($definition) ? ($definition['match'] ?? 'exact') : 'exact';

            if (! isset($modes[$mode])) {
                throw new InvalidArgumentException("Unknown criteria match mode: {$mode}");
            }

            [$template, $binder] = $modes[$mode];
            $key = self::identifier($key, 'criteria key');
            $clause = str_replace('%s', $column, $template);
            $bindValue = str_replace('%k', $key, $binder);

            $lines[] = "\n                if (isset(\$criteria['{$key}']) && \$criteria['{$key}'] !== '') {\n"
                . "                    \$where[] = " . self::phpString($clause) . ";\n"
                . "                    \$bind[] = {$bindValue};\n"
                . "                }";
        }

        return implode('', $lines);
    }

    /**
     * @param  list<array<string, mixed>>  $facts
     */
    private static function renderFacts(array $facts): string
    {
        $lines = [];

        foreach ($facts as $fact) {
            $key = self::identifier($fact['key'] ?? '', 'facts[].key');

            if (! isset($fact['column'])) {
                $why = $fact['defer'] ?? $key;
                $lines[] = "\n                // {$key}: {$why} — no trusted column yet, so facts() stays"
                    . "\n                // silent and the rule defers. Wire a column here to answer it.";

                continue;
            }

            $column = self::identifier($fact['column'], "facts[{$key}].column");
            $say = $fact['say'] ?? null;

            if ($say === null) {
                $lines[] = "\n                if ((\$item['{$column}'] ?? null) !== null) {"
                    . "\n                    \$facts['{$key}'] = (string) \$item['{$column}']; // TODO: phrase this as a sentence"
                    . "\n                }";

                continue;
            }

            $literal = self::phpString($say);
            $lines[] = "\n                if ((\$item['{$column}'] ?? null) !== null) {"
                . "\n                    \$facts['{$key}'] = sprintf({$literal}, \$item['{$column}']);"
                . "\n                }";
        }

        return implode('', $lines);
    }

    private static function className(string $name): string
    {
        $words = preg_split('/[^A-Za-z0-9]+/', trim($name)) ?: [];
        $studly = implode('', array_map(
            static fn(string $word): string => ucfirst(strtolower($word)),
            $words,
        ));

        if (! preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $studly)) {
            throw new InvalidArgumentException("Site name cannot become a class prefix: {$name}");
        }

        return $studly;
    }

    private static function identifier(mixed $value, string $label): string
    {
        $value = (string) $value;

        if (preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $value) !== 1) {
            throw new InvalidArgumentException("Unsafe identifier for {$label}: {$value}");
        }

        return $value;
    }

    private static function phpString(string $value): string
    {
        return "'" . str_replace(['\\', "'"], ['\\\\', "\\'"], $value) . "'";
    }

    private static function commentBlock(string $title, string $body): string
    {
        return "<?php\n\n/**\n * {$title}\n * {$body}\n */\n";
    }
}
